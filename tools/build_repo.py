#!/usr/bin/env python3
"""Build the content of the Kodi repository (what the `repo` branch serves) from add-on zips.

    python3 tools/build_repo.py OUT_DIR ZIP [ZIP ...]

Layout written to OUT_DIR, as `repository.kodiprism/addon.xml` expects (<datadir zip="true">):

    addons.xml                       every add-on's addon.xml, newest version of each id
    addons.xml.md5                   md5 of addons.xml (Kodi re-reads addons.xml when this changes)
    <id>/<id>-<version>.zip          the installable zip
    <id>/<asset path>                icon / fanart listed in <assets>, shown by Kodi before installing
    README.md                        what this branch is

Only the newest version of each add-on id is kept. Output is deterministic for the same input zips.
"""
import hashlib
import os
import re
import shutil
import sys
import xml.etree.ElementTree as ET
import zipfile

README = """# KodiPrism Kodi repository

This branch is generated by `tools/build_repo.py` (workflow `.github/workflows/repo.yml`); do not edit it by hand.
Kodi reads `addons.xml` and downloads the zips from here. To install, see the README on the main branch.
"""


def version_key(v):
    """1.10.0 > 1.9.2; a suffix such as ~beta1 sorts before the plain version."""
    main, _, tag = v.partition("~")
    return tuple(int(x) for x in re.findall(r"\d+", main)), tag == "", tag


def read_addon(path):
    with zipfile.ZipFile(path) as z:
        tops = {n.split("/", 1)[0] for n in z.namelist()}
        if len(tops) != 1:
            raise SystemExit("%s: a Kodi zip has exactly one top folder, found %s" % (path, sorted(tops)))
        top = tops.pop()
        raw = z.read(top + "/addon.xml").decode("utf-8")
    root = ET.fromstring(raw)
    if root.get("id") != top:
        raise SystemExit("%s: folder %s does not match the add-on id %s" % (path, top, root.get("id")))
    return root.get("id"), root.get("version"), raw, root


def build(out, zips):
    newest = {}
    for path in zips:
        addon_id, version, raw, root = read_addon(path)
        if addon_id not in newest or version_key(version) > version_key(newest[addon_id][0]):
            newest[addon_id] = (version, raw, root, path)
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)
    parts = []
    for addon_id in sorted(newest):
        version, raw, root, path = newest[addon_id]
        folder = os.path.join(out, addon_id)
        os.makedirs(folder)
        shutil.copyfile(path, os.path.join(folder, "%s-%s.zip" % (addon_id, version)))
        assets = [e.text.strip() for e in root.iter() if e.tag in ("icon", "fanart", "screenshot", "banner", "clearlogo")
                  and e.text and e.text.strip()]
        with zipfile.ZipFile(path) as z:
            for rel in assets:
                dest = os.path.join(folder, *rel.split("/"))
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                with open(dest, "wb") as fh:
                    fh.write(z.read("%s/%s" % (addon_id, rel)))
        parts.append(re.sub(r"^\s*<\?xml[^>]*\?>\s*", "", raw).strip())
    xml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<addons>\n' + "\n".join(parts) + "\n</addons>\n"
    ET.fromstring(xml.encode("utf-8"))           # must stay well-formed
    data = xml.encode("utf-8")
    with open(os.path.join(out, "addons.xml"), "wb") as fh:
        fh.write(data)
    with open(os.path.join(out, "addons.xml.md5"), "w", encoding="ascii") as fh:
        fh.write(hashlib.md5(data).hexdigest())
    with open(os.path.join(out, "README.md"), "w", encoding="utf-8") as fh:
        fh.write(README)
    for addon_id in sorted(newest):
        print("%s %s" % (addon_id, newest[addon_id][0]))
    return {k: v[0] for k, v in newest.items()}


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    build(sys.argv[1], sys.argv[2:])
